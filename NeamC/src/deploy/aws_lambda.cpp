  f << "    Type: AWS::EFS::FileSystem\n";
  f << "    Properties:\n";
  f << "      PerformanceMode: generalPurpose\n";
  f << "      Encrypted: true\n";
  f << "      Tags:\n";
  f << "        - Key: Name\n";
  f << "          Value: !Sub ${AWS::StackName}-forge-workspace\n\n";
  f << "  ForgeAccessPoint:\n";
  f << "    Type: AWS::EFS::AccessPoint\n";
  f << "    Properties:\n";
  f << "      FileSystemId: !Ref ForgeFileSystem\n";
  f << "      PosixUser:\n";
  f << "        Uid: '1000'\n";
  f << "        Gid: '1000'\n";
  f << "      RootDirectory:\n";
  f << "        CreationInfo:\n";
  f << "          OwnerUid: '1000'\n";
  f << "          OwnerGid: '1000'\n";
  f << "          Permissions: '755'\n";
  f << "        Path: /workspace\n\n";

  f << "  LogGroup:\n";
  f << "    Type: AWS::Logs::LogGroup\n";
  f << "    Properties:\n";
  f << "      LogGroupName: !Sub /aws/lambda/${" << cfn_id << "Function}\n";
  f << "      RetentionInDays: 14\n\n";

  // Outputs
  f << "Outputs:\n";
  f << "  ApiUrl:\n";
  f << "    Description: API Gateway endpoint URL\n";
  f << "    Value: !Sub \"https://${ServerlessHttpApi}.execute-api.${AWS::Region}.amazonaws.com\"\n";
  f << "  FunctionArn:\n";
  f << "    Description: Lambda function ARN\n";
  f << "    Value: !GetAtt " << cfn_id << "Function.Arn\n";
  f << "  FunctionName:\n";
  f << "    Description: Lambda function name\n";
  f << "    Value: !Ref " << cfn_id << "Function\n";

  std::cout << "Generated deploy/lambda/template.yaml\n";
  std::cout << "  PackageType: Image (Lambda Web Adapter)\n";
