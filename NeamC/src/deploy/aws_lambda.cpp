// CloudFormation logical IDs must be alphanumeric.
// Convert "my-agent" → "MyAgent" (PascalCase)
std::string to_cfn_id(const std::string& name)
{
  std::string result;
  bool capitalize = true;
  for (char c : name)
  {
    if (c == '-' || c == '_' || c == '.')
    {
      capitalize = true;
      continue;
    }
    if (capitalize && c >= 'a' && c <= 'z')
    {
      result += static_cast<char>(c - 32);
      capitalize = false;
    }
    else
    {
      result += c;
      capitalize = false;
    }
  }
  return result.empty() ? "NeamAgent" : result;
}
